    exp_thresh = max(4096, 2 * final_dim)

    gt_bpz_v1 = num * (10 ** 15) > 3258805369885465 * den
    gt_bpz_v2 = num * (10 ** 15) > 3258827985920007 * den
    gt_tandon = num * (10 ** 12) > 3258832620353 * den

    lines: list[str] = []
