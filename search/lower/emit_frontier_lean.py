def main() -> int:
    parser = argparse.ArgumentParser(description="Deterministic pure-kernel Lean 4 FrontierLower emitter.")
    parser.add_argument(
        "--witness",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent / "witnesses" / "frontier_c7_d220_partgadget.json",
    )
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[2] / "ShannonC7" / "FrontierLower.lean",
    )
    args = parser.parse_args()
    witness = json.loads(args.witness.read_text(encoding="utf-8"))
    info = _validate_and_replay(witness)
    lean_code = _emit_lean_source(info)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(lean_code, encoding="utf-8")
    lean_bytes = lean_code.encode("utf-8")
    digest = hashlib.sha256(lean_bytes).hexdigest()
    print(f"[emit_frontier_lean] Wrote {args.out} ({len(lean_bytes)} bytes, sha256={digest})")
    return 0


